CREATE TABLE usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    nombre VARCHAR(255) NOT NULL,
    descripcion VARCHAR(255) NOT NULL,
    celular VARCHAR(255) NOT NULL,
    ciudad VARCHAR(255) NOT NULL,
    tipo_usuario VARCHAR(255) NOT NULL,
    bibliokarmas INTEGER NOT NULL,
    imagen_url VARCHAR(255),
    fecha_registro DATE NOT NULL,
    CONSTRAINT uk_usuarios_email UNIQUE (email),
    CONSTRAINT uk_usuarios_celular UNIQUE (celular)
);

CREATE TABLE libros (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(255) NOT NULL,
    descripcion VARCHAR(2000) NOT NULL,
    titulo VARCHAR(255) NOT NULL,
    autor VARCHAR(255) NOT NULL,
    genero VARCHAR(255) NOT NULL,
    estado VARCHAR(255) NOT NULL,
    disponibilidad VARCHAR(255) NOT NULL,
    cantidad_paginas INTEGER NOT NULL,
    isbn VARCHAR(255) NOT NULL,
    idioma VARCHAR(255) NOT NULL,
    editorial VARCHAR(255) NOT NULL,
    fecha_publicacion DATE NOT NULL,
    fecha_agregado DATE NOT NULL,
    imagen_url VARCHAR(255),
    duenio_id INTEGER NOT NULL,
    CONSTRAINT fk_libros_duenio FOREIGN KEY (duenio_id) REFERENCES usuarios (id)
);
