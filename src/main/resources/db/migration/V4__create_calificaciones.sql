CREATE TABLE calificaciones (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libro_id INTEGER NOT NULL,
    usuario_id INTEGER NOT NULL,
    valor INTEGER NOT NULL,
    comentario VARCHAR(2000) NOT NULL,
    CONSTRAINT fk_calificaciones_libro FOREIGN KEY (libro_id) REFERENCES libros (id),
    CONSTRAINT fk_calificaciones_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT ck_calificaciones_valor CHECK (valor BETWEEN 1 AND 5),
    CONSTRAINT uk_calificaciones_libro_usuario UNIQUE (libro_id, usuario_id)
);

